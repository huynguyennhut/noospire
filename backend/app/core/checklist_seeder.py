async def seed_checklist_catalog(session: AsyncSession) -> int:
    """Seeds or updates all 39 Empire Pentest check definitions in the database.
    Guarantees that the full catalog is available for assessment runs.
    """
    current_catalog_ids = {c["check_id"] for c in EMPIRE_CHECKLIST_CATALOG}
    stale_res = await session.execute(
        select(ChecklistDefinition).where(~ChecklistDefinition.check_id.in_(current_catalog_ids))
    )
    stale_items = stale_res.scalars().all()
    for stale in stale_items:
        await session.delete(stale)

    seeded_count = 0
    for check_data in EMPIRE_CHECKLIST_CATALOG:
        res = await session.execute(
            select(ChecklistDefinition).where(ChecklistDefinition.check_id == check_data["check_id"])
        )
        existing = res.scalars().first()
        if existing:
            # Update fields to reflect latest version and guidance
            for key, val in check_data.items():
                setattr(existing, key, val)
        else:
            definition = ChecklistDefinition(**check_data)
            session.add(definition)
            seeded_count += 1

    await session.commit()
    logger.info("Checklist catalog seeded successfully (total definitions: %d, newly created: %d)",
                len(EMPIRE_CHECKLIST_CATALOG), seeded_count)
    return len(EMPIRE_CHECKLIST_CATALOG)


